// Run from any directory: node scripts/build-docs-react.mjs
// Requires the root esbuild devDependency, curl, and tar. Honors TMPDIR.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, version as esbuildVersion } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const pins = JSON.parse(await readFile(new URL("docs-react-vendor.json", import.meta.url), "utf8"));
if (esbuildVersion !== pins.esbuild) {
  throw new Error(`Vendor generation requires esbuild ${pins.esbuild}; found ${esbuildVersion}`);
}
const scratch = await mkdtemp(path.join(tmpdir(), "phren-docs-react-"));
try {
  const licenses = [];
  for (const pkg of pins.packages) {
    const archive = path.join(scratch, `${pkg.name}.tgz`);
    execFileSync("curl", ["--fail", "--silent", "--show-error", "--location", pkg.url, "--output", archive]);
    const integrity = `sha512-${createHash("sha512").update(await readFile(archive)).digest("base64")}`;
    if (integrity !== pkg.integrity) throw new Error(`Integrity mismatch: ${pkg.name}`);
    const directory = path.join(scratch, "node_modules", pkg.name);
    await mkdir(directory, { recursive: true });
    execFileSync("tar", ["-xzf", archive, "--strip-components=1", "-C", directory]);
    const manifest = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8"));
    if (manifest.name !== pkg.name || manifest.version !== pkg.version) {
      throw new Error(`Package identity mismatch: ${pkg.name}@${pkg.version}`);
    }
    licenses.push(`${pkg.name}@${pkg.version}\n${pkg.url}\n\n${await readFile(path.join(directory, "LICENSE"), "utf8")}`);
  }

  const entry = path.join(scratch, "entry.js");
  await writeFile(entry, `import React from "react";
import * as ReactDOM from "react-dom";
import { createRoot, hydrateRoot } from "react-dom/client";
import * as ReactJSXRuntime from "react/jsx-runtime";
window.React = React;
window.ReactDOM = { ...ReactDOM, createRoot, hydrateRoot };
window.ReactJSXRuntime = ReactJSXRuntime;
`);
  const versions = pins.packages.map(({ name, version }) => `${name}@${version}`).join(", ");
  for (const [mode, directory, filename] of [
    ["production", "docs/vendor", "react.production.min.js"],
    ["development", "docs/motion-lab/vendor", "react.development.js"],
  ]) {
    const outputDirectory = path.join(root, directory);
    const result = await build({
      absWorkingDir: scratch,
      entryPoints: ["entry.js"],
      bundle: true,
      format: "iife",
      platform: "browser",
      target: "es2020",
      define: { "process.env.NODE_ENV": JSON.stringify(mode) },
      minify: mode === "production",
      legalComments: "inline",
      write: false,
      banner: { js: `/*! ${versions}; ${mode}; esbuild@${pins.esbuild}.\n * Generated by scripts/build-docs-react.mjs. MIT licenses: react.LICENSE.txt. */` },
    });
    await writeFile(path.join(outputDirectory, filename), result.outputFiles[0].contents);
    await writeFile(path.join(outputDirectory, "react.LICENSE.txt"), licenses.join("\n\n---\n\n"));
    console.log(`${directory}/${filename}`);
  }
} finally {
  await rm(scratch, { recursive: true, force: true });
}
