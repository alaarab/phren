#!/usr/bin/env node
// Bundles the shared 3D graph renderer into the iOS app's resources.
//
// The renderer in packages/cli/browser/graph/* is the same code the web memory
// UI and the VS Code webview run; this produces the same IIFE for the app's
// WKWebView, so the phone renders from one implementation rather than a
// transcription. Mirrors bundleBrowserAssets() in scripts/build.mjs.
//
// Run from apps/ios after changing anything under packages/cli/browser/:
//   node scripts/bundle-graph.mjs
//
// The output is gitignored: regenerate it rather than committing 1.4 MB of
// minified JS, exactly as PhrenKit's fixtures are regenerated.
//
// Xcode runs this as a pre-build phase based on dependency analysis. Its
// inputs are scripts/graph-inputs.xcfilelist, which every run rewrites from
// esbuild's metafile: the repository sources the bundle actually read, this
// script and the lockfile (standing in for node_modules). An unchanged build
// then skips node entirely; graph-bundle-size.test.ts fails when the
// committed list drifts from the sources.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const iosRoot = path.resolve(here, "..");
const repoRoot = path.resolve(iosRoot, "../..");
const browserRoot = path.join(repoRoot, "packages/cli/browser");
const outDir = path.join(iosRoot, "Phren/Resources/graph");
export const inputListPath = path.join(here, "graph-inputs.xcfilelist");

const entry = path.join(browserRoot, "memory-ui-graph-app.ts");
if (!fs.existsSync(entry)) {
  console.error(`Renderer entry not found: ${entry}`);
  process.exit(1);
}

// The app uses WebGL and its postprocessing composer. three-render-objects
// also imports an optional WebGPU backend, which would otherwise be retained.
export async function bundleGraph(write = true) {
  if (write) fs.mkdirSync(outDir, { recursive: true });
  return build({
    absWorkingDir: iosRoot,
    bundle: true,
    entryPoints: [entry],
    format: "iife",
    legalComments: "none",
    minify: true,
    outfile: path.join(outDir, "phren-graph.js"),
    platform: "browser",
    target: ["safari17"],
    alias: { "three/webgpu": path.join(browserRoot, "graph/webgl-only.ts") },
    metafile: true,
    write,
  });
}

/** The Xcode input file list for a bundle: every repository source esbuild
 * read (dependencies are covered by the lockfile), as $(SRCROOT) paths. */
export function graphInputList(metafile) {
  const sources = Object.keys(metafile.inputs)
    .map(input => path.resolve(iosRoot, input))
    .filter(file => !file.split(path.sep).includes("node_modules"))
    .map(file => path.relative(iosRoot, file).split(path.sep).join("/"));
  const files = [...new Set([...sources, "scripts/bundle-graph.mjs", "../../pnpm-lock.yaml"])].sort();
  return "# Generated by scripts/bundle-graph.mjs: the graph bundle's inputs.\n"
    + files.map(file => `$(SRCROOT)/${file}`).join("\n") + "\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const result = await bundleGraph();
  const list = graphInputList(result.metafile);
  let existing = "";
  try { existing = fs.readFileSync(inputListPath, "utf8"); } catch { /* missing, or outside the sandbox */ }
  if (existing !== list) {
    // Xcode's script sandbox only lets the phase write its declared output
    // (and read declared inputs), so a changed list is written from a plain
    // run and only warned about inside Xcode.
    try { fs.writeFileSync(inputListPath, list); } catch {
      console.warn("warning: the graph's inputs changed; run `node scripts/bundle-graph.mjs` in apps/ios and commit scripts/graph-inputs.xcfilelist");
    }
  }
  const bytes = fs.statSync(path.join(outDir, "phren-graph.js")).size;
  console.log(`Wrote Phren/Resources/graph/phren-graph.js (${bytes} bytes)`);
}
